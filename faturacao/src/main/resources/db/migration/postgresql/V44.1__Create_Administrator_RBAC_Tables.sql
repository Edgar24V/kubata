-- Preparar as tabelas RBAC utilizadas pelas migrações do Administrator.
-- Executa depois do catálogo V47 e antes das concessões V48/V49.
-- A forma INSERT ... WHERE NOT EXISTS também é suportada pelo H2 usado nos testes.

CREATE TABLE IF NOT EXISTS adm_perfil_acesso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    descricao VARCHAR(100) NOT NULL,
    observacoes VARCHAR(500),
    sistema BOOLEAN DEFAULT FALSE,
    activo BOOLEAN DEFAULT TRUE,
    empresa_id BIGINT
);

CREATE TABLE IF NOT EXISTS adm_permissao_perfil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id BIGINT NOT NULL,
    modulo VARCHAR(50) NOT NULL,
    recurso VARCHAR(50) NOT NULL,
    operacao VARCHAR(50) NOT NULL,
    permitido BOOLEAN DEFAULT FALSE NOT NULL,
    valor_restricao VARCHAR(255),
    CONSTRAINT uk_permissao_perfil UNIQUE (perfil_id, modulo, recurso, operacao),
    CONSTRAINT fk_permissao_perfil FOREIGN KEY (perfil_id)
        REFERENCES adm_perfil_acesso(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS user_perfis (
    user_id BIGINT NOT NULL,
    perfil_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, perfil_id),
    CONSTRAINT fk_user_perfis_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_perfis_perfil FOREIGN KEY (perfil_id)
        REFERENCES adm_perfil_acesso(id) ON DELETE CASCADE
);

INSERT INTO adm_perfil_acesso (codigo, descricao, sistema, activo)
SELECT 'ADMIN', 'Administrador do Sistema', TRUE, TRUE
WHERE NOT EXISTS (SELECT 1 FROM adm_perfil_acesso WHERE codigo = 'ADMIN');

INSERT INTO adm_perfil_acesso (codigo, descricao, sistema, activo)
SELECT 'CONSULTOR', 'Perfil de Consulta Global', TRUE, TRUE
WHERE NOT EXISTS (SELECT 1 FROM adm_perfil_acesso WHERE codigo = 'CONSULTOR');

INSERT INTO adm_permissao_perfil (perfil_id, modulo, recurso, operacao, permitido)
SELECT id, 'ADMINISTRATOR', 'TODOS', 'VER', TRUE
FROM adm_perfil_acesso p
WHERE p.codigo = 'ADMIN'
  AND NOT EXISTS (
      SELECT 1 FROM adm_permissao_perfil e
      WHERE e.perfil_id = p.id
        AND e.modulo = 'ADMINISTRATOR'
        AND e.recurso = 'TODOS'
        AND e.operacao = 'VER'
  );
